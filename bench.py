#!/usr/bin/env python3
"""Runs the whole config matrix over every image in a folder.

Data-driven: it benchmarks whatever is in `samples/bench/`, so adding a
new test case means dropping a file in, not editing this script.

    python3 bench.py                      # samples/bench -> bench-out/
    python3 bench.py --input dir --out dir
    python3 bench.py --only 02,04         # fixtures whose name contains these

Writes per-image SVGs, a contact sheet, and RESULTS.md.
"""

import argparse
import os
import time

from PIL import Image, ImageDraw

from vectorlab import VectorizeOptions, VectorizeRejected, vectorize_image
from vectorlab.pipeline import MODE_FULL_COLOR, MODE_GRAYSCALE, MODE_MONOCHROME
from verify import score

IMAGE_SUFFIXES = (".png", ".jpg", ".jpeg", ".webp", ".bmp")

# Each preset is a named policy, not a pile of knobs. These are the
# configurations worth comparing on every input.
PRESETS = (
    ("flat-6", VectorizeOptions(mode=MODE_FULL_COLOR, color_count=6)),
    ("flat-12", VectorizeOptions(mode=MODE_FULL_COLOR, color_count=12)),
    (
        "lineart",
        VectorizeOptions(mode=MODE_FULL_COLOR, color_count=6, upscale=2.0, max_dimension=1200),
    ),
    (
        "denoised",
        VectorizeOptions(mode=MODE_FULL_COLOR, color_count=16, presmooth=3, min_region_area=4),
    ),
    (
        "poster",
        VectorizeOptions(
            mode=MODE_FULL_COLOR,
            color_count=6,
            simplify_epsilon=2.8,
            min_region_area=200,
            corner_threshold_degrees=60.0,
        ),
    ),
    ("gray-4", VectorizeOptions(mode=MODE_GRAYSCALE, gray_count=4)),
    ("mono", VectorizeOptions(mode=MODE_MONOCHROME, threshold=140, upscale=2.0, max_dimension=1200)),
)


def _discover(folder, only):
    names = sorted(
        name
        for name in os.listdir(folder)
        if name.lower().endswith(IMAGE_SUFFIXES) and not name.startswith(".")
    )
    if only:
        wanted = [token.strip() for token in only.split(",") if token.strip()]
        names = [name for name in names if any(token in name for token in wanted)]
    return names


def _run_one(image_path, preset_name, options, out_dir):
    svg_path = os.path.join(out_dir, f"{preset_name}.svg")
    started = time.perf_counter()
    try:
        result = vectorize_image(image_path, options)
    except VectorizeRejected as rejected:
        return {
            "preset": preset_name,
            "rejected": rejected.reason,
            "shapes": rejected.region_count,
            "segments": 0,
            "bytes": 0,
            "seconds": time.perf_counter() - started,
            "agreement": 0.0,
            "delta": 0.0,
        }
    elapsed = time.perf_counter() - started

    with open(svg_path, "w", encoding="utf-8") as handle:
        handle.write(result.svg)

    agreement, delta, rendered = score(image_path, svg_path)
    rendered.save(os.path.join(out_dir, f"{preset_name}.png"))

    return {
        "preset": preset_name,
        "shapes": result.shape_count,
        "segments": result.path_segment_count,
        "bytes": os.path.getsize(svg_path),
        "seconds": elapsed,
        "agreement": agreement * 100.0,
        "delta": delta,
        "rejected": "",
    }


def _contact_sheet(image_path, rows, out_dir, cell=260):
    """Source plus every preset's render, side by side."""
    tiles = [(Image.open(image_path).convert("RGB"), "source")]
    for row in rows:
        render = os.path.join(out_dir, f"{row['preset']}.png")
        if os.path.exists(render):
            tiles.append((Image.open(render).convert("RGB"), row["preset"]))

    columns = min(4, len(tiles))
    sheet_rows = (len(tiles) + columns - 1) // columns
    sheet = Image.new(
        "RGB", (columns * (cell + 10) + 10, sheet_rows * (cell + 34) + 10), (255, 255, 255)
    )
    draw = ImageDraw.Draw(sheet)

    for index, (tile, label) in enumerate(tiles):
        tile = tile.copy()
        tile.thumbnail((cell, cell), Image.LANCZOS)
        column = index % columns
        row_index = index // columns
        left = 10 + column * (cell + 10)
        top = 10 + row_index * (cell + 34)
        sheet.paste(tile, (left, top))
        draw.text((left + 2, top + cell + 6), label, fill=(40, 40, 40))

    path = os.path.join(out_dir, "contact-sheet.png")
    sheet.save(path)
    return path


def _write_report(all_results, out_root):
    lines = [
        "# Benchmark results",
        "",
        "Generated by `bench.py`. Scores come from `verify.py`, which "
        "rasterises our own output and compares it per pixel.",
        "",
        "**Treat the score as a regression guard, not a quality metric.** "
        "A better-looking trace often scores worse, and roughly 3 points "
        "of every score is the verifier's own half-pixel fill convention.",
        "",
    ]

    for image_name, rows in all_results:
        lines.append(f"## {image_name}")
        lines.append("")
        lines.append("| Preset | Shapes | Segments | Size | Time | Agreement |")
        lines.append("|---|---|---|---|---|---|")
        scored = [row for row in rows if not row["rejected"]]
        best = max(scored, key=lambda row: row["agreement"]) if scored else None
        for row in rows:
            if row["rejected"]:
                lines.append(
                    f"| {row['preset']} | — | — | — | {row['seconds']:.2f}s "
                    f"| rejected: {row['rejected']} |"
                )
                continue
            marker = " **" if best and row is best else ""
            closer = "**" if marker else ""
            lines.append(
                f"|{marker}{row['preset']}{closer} "
                f"| {row['shapes']} | {row['segments']} "
                f"| {row['bytes'] / 1024:.0f} KB | {row['seconds']:.2f}s "
                f"| {row['agreement']:.1f}% |"
            )
        lines.append("")

    path = os.path.join(out_root, "RESULTS.md")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    return path


def main(argv=None):
    parser = argparse.ArgumentParser(description="Run the config matrix over a folder of images")
    parser.add_argument("--input", default="samples/bench", help="folder of source images")
    parser.add_argument("--out", default="bench-out", help="where results are written")
    parser.add_argument("--only", default="", help="comma-separated name filters")
    args = parser.parse_args(argv)

    if not os.path.isdir(args.input):
        parser.error(f"no such folder: {args.input} — run make_test_image.py first")

    names = _discover(args.input, args.only)
    if not names:
        parser.error(f"no images found in {args.input}")

    os.makedirs(args.out, exist_ok=True)
    all_results = []

    for name in names:
        image_path = os.path.join(args.input, name)
        stem = os.path.splitext(name)[0]
        out_dir = os.path.join(args.out, stem)
        os.makedirs(out_dir, exist_ok=True)

        print(f"\n{name}")
        rows = []
        for preset_name, options in PRESETS:
            row = _run_one(image_path, preset_name, options, out_dir)
            rows.append(row)
            if row["rejected"]:
                print(f"  {preset_name:9s} rejected — {row['rejected']}")
            else:
                print(
                    f"  {preset_name:9s} {row['shapes']:5d} shapes "
                    f"{row['segments']:6d} seg  {row['seconds']:5.2f}s  "
                    f"{row['agreement']:5.1f}%"
                )

        _contact_sheet(image_path, rows, out_dir)
        all_results.append((name, rows))

    report = _write_report(all_results, args.out)
    print(f"\nwrote {report}")
    print(f"contact sheets under {args.out}/<image>/contact-sheet.png")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
